#!/usr/bin/env python3
"""Render the panel bitmaps i2600-scand compiles in, into panel-bitmaps.h.

The scanner holds no fonts: a panel message is a 128x48 bitmap the host
uploads (NATIVES-BACKEND.md section 14).  The daemon has to show its text
without any data file beside it, so the bitmaps are rendered here with the
same code tools/lcd-text.py uses and checked in as C arrays.

  python3 gen-panel.py > panel-bitmaps.h

Needs PIL and a DejaVu or Noto font; re-run it only when a text changes.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "tools"))

import importlib.util

_spec = importlib.util.spec_from_file_location(
    "lcd_text", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "..", "tools", "lcd-text.py"))
lcd_text = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lcd_text)

# name, region, screen, reserve_top, lines.  Region 2 screen 3 is the one the
# device draws while it sleeps, so that is where the waiting text goes; the
# region 4 screens are its action line, which needs six rows left free.
BITMAPS = [
    ("ready",   2, 3, 0, ["Bereit"]),
    ("scanning", 2, 1, 0, ["Scannt..."]),
]


def main():
    print("/* Generated by gen-panel.py -- do not edit. */")
    print("#ifndef I2600_PANEL_BITMAPS_H")
    print("#define I2600_PANEL_BITMAPS_H")
    print()
    print("/* 128x48, six pages of eight stacked rows, one byte per column,")
    print(" * bit 0 topmost -- the format i2600_lcd_write() wants. */")
    for name, region, screen, top, lines in BITMAPS:
        data = lcd_text.to_pages(lcd_text.render(lines, top))
        assert len(data) == 768, len(data)
        print()
        print("/* %s -- region %d screen %d */" % (" / ".join(lines), region, screen))
        print("#define I2600_PANEL_%s_REGION %d" % (name.upper(), region))
        print("#define I2600_PANEL_%s_SCREEN %d" % (name.upper(), screen))
        print("static const unsigned char i2600_panel_%s[768] = {" % name)
        for i in range(0, 768, 12):
            row = ", ".join("0x%02x" % b for b in data[i:i + 12])
            print("\t%s," % row)
        print("};")
    print()
    print("#endif /* I2600_PANEL_BITMAPS_H */")


if __name__ == "__main__":
    main()
