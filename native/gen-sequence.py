"""Generate sequence.h: the vendor control-transfer table of a reference capture.

The i2600 initialisation and scan setup programs roughly 360 vendor control
transfers worth of camera pages, FPGA registers and configuration blocks. Their
*values* are documented in PROTOKOLL.md section 4a and the analysis files, but
hand-retyping them would add transcription risk for no gain. So the table is
generated byte-exactly from the reference capture, grouped into named phases so
the grabber can skip individual groups and find out which ones actually matter.

Usage: python3 gen-sequence.py ../captures/pcapng/b-simplex-lineart-200.pcapng > sequence.h
"""
import sys, os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'tools', 'protocol'))
import ctrl

# Opcode names from PROTOKOLL.md section 4 (original vendor function names).
OPNAME = {
    0x00: 'OP_GET_STATUS',            0x02: 'OP_GET_FIRMWARE_VERSIONS',
    0x03: 'OP_GET_MACHINE_CONSTANTS', 0x10: 'OP_SCANNER_OPERATION',
    0x11: 'OP_LAMP',                  0x16: 'OP_SET_BUTTON_SEQUENCE',
    0x17: 'OP_START_CAPTURE',         0x1b: 'OP_SCANNER_OPERATION_0D',
    0x1f: 'OP_SET_TIME',              0x30: 'OP_SCANNER_CONFIGURATION',
    0x31: 'OP_ENERGY_STAR',           0x32: 'OP_LOW_POWER_TIMEOUT',
    0x33: 'OP_METERS',                0x34: 'OP_END_OF_LINE',
    0x35: 'OP_NVRAM',                 0x36: 'OP_BOARD_SERIAL_NUMBER',
    0x37: 'OP_SESSION_INFO',          0x3a: 'OP_INTERRUPT_EVENTS',
    0x45: 'OP_BATCH_DATA',            0x62: 'OP_OCP_BLOCK',
    0xa3: 'OP_FPGA_REGISTER',         0xe0: 'OP_CAMERA_REGISTER',
    0xe3: 'OP_FLASH_MEMORY',
}

# Phase boundaries, as indices into the vendor-transfer list of
# b-simplex-lineart-200.pcapng.  (phase table, group name, first, last)
GROUPS = [
    ('open',        'ident',       0,   9),   # GetStatus/FirmwareVersions/EndOfLine/Serial/Session/SetTime/MachineConstants/NvRam
    ('open',        'docid',      10,  11),   # a3 da27/db27 = document id
    ('open',        'flash',      12,  12),   # e3 ReadFlashMemory wIndex=0xfc00
    ('open',        'session_rd', 13,  14),   # 2x GetSessionInfo
    ('open',        'standby',    15,  73),   # SetAfeStandby, both cameras + a3 d901
    ('open',        'housekeep',  74,  97),   # BatchData, lamp off, OCP blocks, NvRam, meters
    ('open',        'intrevents', 98,  98),   # 3a StartInterruptEvents
    ('open',        'op1b',       99,  99),   # 1b ScannerOperation 0x0d
    ('prepare',     'poll1',     100, 105),   # status polls + low power timeout
    ('prepare',     'estar',     106, 106),   # SetEnergyStar
    ('prepare',     'poll2',     107, 115),   # status polls
    ('prepare',     'lamp',      116, 116),   # 11 wValue=1, lamp on
    ('prepare',     'batch',     117, 119),   # SetBatchData + NvRam read
    ('prepare',     'lamp2',     120, 120),   # 11 wValue=1 again
    ('prepare',     'docid2',    121, 124),   # a3 da27/db27 read back and rewrite
    ('prepare',     'session_w', 125, 126),   # SetSessionInfo
    ('prepare',     'd9regs',    127, 137),   # d9xx image chain + dc00 (78 bytes)
    ('prepare',     'campages',  138, 228),   # camera pages 0..6, both cameras
    ('prepare',     'gains',     229, 237),   # AFE gains, page 1 register 0
    ('prepare',     'daregs',    238, 254),   # daxx/dbxx FPGA: width, page detect, crop
    ('prepare',     'wbal',      255, 270),   # white balance: d901=0x28, dd0a/dd0b
    ('ref_config',  'ref_cfg',   271, 271),   # 0x30 SDmScanConfig, shutter pass
    ('scan_prep',   'scan_prep', 275, 277),   # a3 da0e/da06/da07 before the real pass
    ('scan_config', 'scan_cfg',  278, 278),   # 0x30 SDmScanConfig, normal pass
    ('teardown',    'teardown',  280, 361),   # stops, dc00, lamp off, standby, 3a off
]


def main():
    cap = sys.argv[1]
    ts = ctrl.transfers(cap)
    v = [t for t in ts if (t['bmr'] & 0x60) == 0x40]

    bad = [t for t in v if len(t['data']) != t['wlen']]
    if bad:
        sys.exit('refusing to generate: %d transfers have truncated payloads' % len(bad))

    tables = []          # (table name, [(group, transfer)])
    for tbl, grp, lo, hi in GROUPS:
        if not tables or tables[-1][0] != tbl:
            tables.append((tbl, []))
        for t in v[lo:hi + 1]:
            tables[-1][1].append((grp, t))

    groups = []
    for _, grp, _, _ in GROUPS:
        if grp not in groups:
            groups.append(grp)

    blob = bytearray()
    blob_off = {}

    def intern(data):
        if not data:
            return 0
        key = bytes(data)
        if key not in blob_off:
            blob_off[key] = len(blob)
            blob.extend(key)
        return blob_off[key]

    out = []
    w = out.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Copyright (C) 2026 Thomas Parthe */')
    w('/* Generated by gen-sequence.py from %s -- do not edit. */'
      % os.path.basename(cap))
    w('#ifndef I2600_SEQUENCE_H')
    w('#define I2600_SEQUENCE_H')
    w('')
    w('#include <stdint.h>')
    w('')
    w('/* Vendor opcodes, named after the vendor functions that issue them')
    w(' * (devicemanager.so, see PROTOKOLL.md section 4). */')
    for op in sorted(OPNAME):
        w('#define %-28s 0x%02x' % (OPNAME[op], op))
    w('')
    w('#define RT_HOST_TO_DEVICE            0x40')
    w('#define RT_DEVICE_TO_HOST            0xc0')
    w('')
    w('enum i2600_group {')
    for g in groups:
        w('\tGRP_%s,' % g.upper())
    w('\tGRP_COUNT')
    w('};')
    w('')
    w('static const char *const i2600_group_name[GRP_COUNT] = {')
    for g in groups:
        w('\t"%s",' % g)
    w('};')
    w('')
    w('struct i2600_step {')
    w('\tuint8_t  group;')
    w('\tuint8_t  bmrt;      /* RT_HOST_TO_DEVICE or RT_DEVICE_TO_HOST */')
    w('\tuint8_t  opcode;')
    w('\tuint16_t wvalue;')
    w('\tuint16_t windex;')
    w('\tuint16_t wlength;')
    w('\tuint32_t payload;   /* offset into i2600_payloads, 0 if wlength == 0 */')
    w('};')
    w('')

    rendered = []
    for name, steps in tables:
        lines = []
        for grp, t in steps:
            off = intern(t['data']) if (t['bmr'] & 0x80) == 0 else 0
            lines.append('\t{ GRP_%-10s %s, %-26s 0x%04x, 0x%04x, %5d, %7d },'
                         % (grp.upper() + ',',
                            'RT_HOST_TO_DEVICE' if (t['bmr'] & 0x80) == 0
                            else 'RT_DEVICE_TO_HOST',
                            OPNAME.get(t['breq'], '0x%02x' % t['breq']) + ',',
                            t['wval'], t['widx'], t['wlen'], off))
        rendered.append((name, lines))

    w('static const uint8_t i2600_payloads[] = {')
    for i in range(0, len(blob), 16):
        w('\t' + ' '.join('0x%02x,' % b for b in blob[i:i + 16]))
    w('};')
    w('')
    for name, lines in rendered:
        w('static const struct i2600_step i2600_seq_%s[] = {' % name)
        for l in lines:
            w(l)
        w('};')
        w('')
    w('#endif /* I2600_SEQUENCE_H */')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
