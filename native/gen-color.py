"""Generate sequence-color.h: the complete colour sequence, position-faithful.

sequence.h holds the simplex vendor sequence, grouped into named phases by
hand-checked indices.  Colour is not a few extra registers on top of it: the
vendor interleaves the two cameras throughout, and an earlier attempt that
appended rear-camera groups to the simplex tables produced a rear channel
that returned a footer but no image lines.

So this generator does for vendor-color.pcapng what gen-sequence.py
does for the simplex capture: it emits the whole transfer list in capture
order, split into the same phases, byte-exactly.  The phase boundaries are
found by landmark rather than by index, because the colour capture has 405
vendor transfers against the simplex 362 and every fixed index would shift.

Skipped on purpose are the transfers i2600-grab issues itself around the
passes: ScannerOperation (0x10) and StartCapture (0x17) between the two
SDmScanConfig blocks -- exactly what gen-sequence.py leaves out there too.

Usage: python3 gen-color.py ../captures/pcapng/vendor-color.pcapng \
           > sequence-color.h
"""
import sys, os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'tools', 'protocol'))
import ctrl

OP_SCANNER_OPERATION     = 0x10
OP_START_CAPTURE         = 0x17
OP_SCANNER_CONFIGURATION = 0x30
OP_SCANNER_OPERATION_0D  = 0x1b

cap = sys.argv[1]
v = [t for t in ctrl.transfers(cap) if (t['bmr'] & 0x60) == 0x40]
bad = [t for t in v if len(t['data']) != t['wlen']]
if bad:
    sys.exit('refusing to generate: %d truncated payloads' % len(bad))

def find(pred, start=0):
    for i in range(start, len(v)):
        if pred(v[i]):
            return i
    sys.exit('landmark not found')

# Landmarks.  open ends with ScannerOperation 0x0d, as in the simplex table;
# the two 120-byte SDmScanConfig blocks delimit reference and scan pass.
i_op1b = find(lambda t: t['breq'] == OP_SCANNER_OPERATION_0D)
i_ref  = find(lambda t: t['breq'] == OP_SCANNER_CONFIGURATION and t['wlen'] == 120)
i_scan = find(lambda t: t['breq'] == OP_SCANNER_CONFIGURATION and t['wlen'] == 120,
              i_ref + 1)

own = (OP_SCANNER_OPERATION, OP_START_CAPTURE)   # issued by i2600-grab itself

phases = [
    ('open',        v[:i_op1b + 1]),
    ('prepare',     v[i_op1b + 1:i_ref]),
    ('ref_config',  [v[i_ref]]),
    ('scan_prep',   [t for t in v[i_ref + 1:i_scan] if t['breq'] not in own]),
    ('scan_config', [v[i_scan]]),
    ('teardown',    [t for t in v[i_scan + 1:] if t['breq'] not in own]),
]

blob = bytearray()
off = {}
def intern(data):
    if not data:
        return 0
    k = bytes(data)
    if k not in off:
        off[k] = len(blob)
        blob.extend(k)
    return off[k]

tables = [(name, [(t['breq'], t['wval'], t['widx'], t['wlen'], intern(t['data']),
                   'RT_DEVICE_TO_HOST' if (t['bmr'] & 0x80) else 'RT_HOST_TO_DEVICE')
                  for t in steps])
          for name, steps in phases]

w = print
w('/* Generated by gen-color.py from %s -- do not edit. */'
  % os.path.basename(cap))
w('#ifndef I2600_SEQUENCE_COLOR_H')
w('#define I2600_SEQUENCE_COLOR_H')
w('')
w('#include <stdint.h>')
w('')
w('/* The colour sequence shares one group: the per-group measurements in')
w(' * NATIVES-BACKEND.md section 5 were made against the simplex table. */')
w('#define GRP_COLOR  GRP_COUNT')
w('')
w('static const uint8_t i2600_color_payloads[] = {')
for i in range(0, len(blob), 16):
    w('\t' + ' '.join('0x%02x,' % b for b in blob[i:i + 16]))
w('};')
w('')
for name, steps in tables:
    w('/* %s: %d transfers */' % (name, len(steps)))
    w('static const struct i2600_step i2600_col_%s[] = {' % name)
    for breq, wval, widx, wlen, p, rt in steps:
        w('\t{ GRP_COLOR, %-18s 0x%02x, 0x%04x, 0x%04x, %5d, %7d },'
          % (rt + ',', breq, wval, widx, wlen, p))
    w('};')
    w('')
w('/* StartCapture carries the camera mask: 1 = front only, 3 = both. */')
w('#define I2600_COLOR_START_CAPTURE  %d'
  % next(t['wval'] for t in v if t['breq'] == OP_START_CAPTURE))
w('')
w('#endif /* I2600_SEQUENCE_COLOR_H */')
